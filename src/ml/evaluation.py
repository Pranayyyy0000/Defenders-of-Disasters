"""
ML Evaluation Module for Defenders of Disasters.

CRITICAL METHODOLOGY NOTE:
The labels generated by heuristic rules (e.g. humidity * 0.5 + soil_moisture * 100 >= threshold,
or heat_index >= mean) are PROXY LABELS, not ground-truth historical disaster events.
Evaluating models against these labels verifies whether the classifier learns the
heuristic risk boundary, not empirical disaster occurrence.
"""

from dataclasses import dataclass, asdict
from typing import List, Dict, Any, Tuple, Optional
import random
import math
from src.services.weather_service import WeatherResult, WeatherService


PROXY_LABEL_DISCLAIMER = (
    "METHODOLOGY DISCLAIMER: Rule-generated labels are heuristic PROXY LABELS, "
    "not empirical historical disaster ground truth. These labels simulate domain-expert "
    "risk scoring rules. Model performance reflects fidelity to this proxy boundary."
)


@dataclass
class ConfusionMatrix:
    true_negative: int
    false_positive: int
    false_negative: int
    true_positive: int

    def to_matrix(self) -> List[List[int]]:
        return [
            [self.true_negative, self.false_positive],
            [self.false_negative, self.true_positive],
        ]

    def to_dict(self) -> Dict[str, int]:
        return asdict(self)


@dataclass
class ClassificationClassMetrics:
    precision: float
    recall: float
    f1_score: float
    support: int


@dataclass
class ClassificationReport:
    classes: Dict[str, ClassificationClassMetrics]
    accuracy: float
    macro_avg: ClassificationClassMetrics
    weighted_avg: ClassificationClassMetrics
    disclaimer: str = PROXY_LABEL_DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        return {
            "classes": {k: asdict(v) for k, v in self.classes.items()},
            "accuracy": self.accuracy,
            "macro_avg": asdict(self.macro_avg),
            "weighted_avg": asdict(self.weighted_avg),
            "disclaimer": self.disclaimer,
        }

    def format_text(self) -> str:
        lines = [
            f"{'Class':<15} {'Precision':<10} {'Recall':<10} {'F1-Score':<10} {'Support':<8}",
            "-" * 55,
        ]
        for name, m in self.classes.items():
            lines.append(
                f"{name:<15} {m.precision:<10.3f} {m.recall:<10.3f} {m.f1_score:<10.3f} {m.support:<8}"
            )
        lines.append("-" * 55)
        lines.append(
            f"{'accuracy':<15} {'':<10} {'':<10} {self.accuracy:<10.3f} {self.macro_avg.support:<8}"
        )
        lines.append(
            f"{'macro avg':<15} {self.macro_avg.precision:<10.3f} {self.macro_avg.recall:<10.3f} {self.macro_avg.f1_score:<10.3f} {self.macro_avg.support:<8}"
        )
        lines.append(
            f"{'weighted avg':<15} {self.weighted_avg.precision:<10.3f} {self.weighted_avg.recall:<10.3f} {self.weighted_avg.f1_score:<10.3f} {self.weighted_avg.support:<8}"
        )
        return "\n".join(lines)


@dataclass
class EvaluationMetrics:
    accuracy: float
    precision: float
    recall: float
    f1: float
    confusion_matrix: ConfusionMatrix
    classification_report: ClassificationReport
    feature_importance: Dict[str, float]
    train_size: int
    test_size: int
    random_state: int
    is_proxy_label: bool = True
    disclaimer: str = PROXY_LABEL_DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        return {
            "accuracy": self.accuracy,
            "precision": self.precision,
            "recall": self.recall,
            "f1": self.f1,
            "confusion_matrix": self.confusion_matrix.to_dict(),
            "classification_report": self.classification_report.to_dict(),
            "feature_importance": self.feature_importance,
            "train_size": self.train_size,
            "test_size": self.test_size,
            "random_state": self.random_state,
            "is_proxy_label": self.is_proxy_label,
            "disclaimer": self.disclaimer,
        }


def compute_accuracy(y_true: List[int], y_pred: List[int]) -> float:
    if not y_true:
        return 0.0
    correct = sum(1 for yt, yp in zip(y_true, y_pred) if yt == yp)
    return round(correct / len(y_true), 4)


def compute_confusion_matrix(y_true: List[int], y_pred: List[int]) -> ConfusionMatrix:
    tn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 0)
    fp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 0 and yp == 1)
    fn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 0)
    tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == 1 and yp == 1)
    return ConfusionMatrix(true_negative=tn, false_positive=fp, false_negative=fn, true_positive=tp)


def compute_precision(y_true: List[int], y_pred: List[int], positive_class: int = 1) -> float:
    tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == positive_class and yp == positive_class)
    fp = sum(1 for yt, yp in zip(y_true, y_pred) if yt != positive_class and yp == positive_class)
    if tp + fp == 0:
        return 0.0
    return round(tp / (tp + fp), 4)


def compute_recall(y_true: List[int], y_pred: List[int], positive_class: int = 1) -> float:
    tp = sum(1 for yt, yp in zip(y_true, y_pred) if yt == positive_class and yp == positive_class)
    fn = sum(1 for yt, yp in zip(y_true, y_pred) if yt == positive_class and yp != positive_class)
    if tp + fn == 0:
        return 0.0
    return round(tp / (tp + fn), 4)


def compute_f1(precision: float, recall: float) -> float:
    if precision + recall == 0.0:
        return 0.0
    return round(2 * (precision * recall) / (precision + recall), 4)


def build_classification_report(
    y_true: List[int], y_pred: List[int], class_labels: Dict[int, str]
) -> ClassificationReport:
    accuracy = compute_accuracy(y_true, y_pred)
    total_samples = len(y_true)

    class_metrics: Dict[str, ClassificationClassMetrics] = {}
    supports: List[int] = []
    precisions: List[float] = []
    recalls: List[float] = []
    f1s: List[float] = []

    for cls_val, cls_name in class_labels.items():
        support = sum(1 for yt in y_true if yt == cls_val)
        prec = compute_precision(y_true, y_pred, positive_class=cls_val)
        rec = compute_recall(y_true, y_pred, positive_class=cls_val)
        f1 = compute_f1(prec, rec)

        class_metrics[cls_name] = ClassificationClassMetrics(
            precision=prec, recall=rec, f1_score=f1, support=support
        )
        supports.append(support)
        precisions.append(prec)
        recalls.append(rec)
        f1s.append(f1)

    # Macro average
    macro_prec = round(sum(precisions) / len(precisions), 4) if precisions else 0.0
    macro_rec = round(sum(recalls) / len(recalls), 4) if recalls else 0.0
    macro_f1 = compute_f1(macro_prec, macro_rec)
    macro_avg = ClassificationClassMetrics(
        precision=macro_prec, recall=macro_rec, f1_score=macro_f1, support=total_samples
    )

    # Weighted average
    weighted_prec = (
        round(sum(p * s for p, s in zip(precisions, supports)) / total_samples, 4)
        if total_samples > 0
        else 0.0
    )
    weighted_rec = (
        round(sum(r * s for r, s in zip(recalls, supports)) / total_samples, 4)
        if total_samples > 0
        else 0.0
    )
    weighted_f1 = compute_f1(weighted_prec, weighted_rec)
    weighted_avg = ClassificationClassMetrics(
        precision=weighted_prec, recall=weighted_rec, f1_score=weighted_f1, support=total_samples
    )

    return ClassificationReport(
        classes=class_metrics,
        accuracy=accuracy,
        macro_avg=macro_avg,
        weighted_avg=weighted_avg,
    )


def train_test_split_dataset(
    X: List[List[float]],
    y: List[int],
    test_size: float = 0.25,
    random_state: int = 42,
) -> Tuple[List[List[float]], List[List[float]], List[int], List[int]]:
    """
    Splits dataset into training and testing sets with a reproducible random_state.
    """
    n = len(X)
    if n == 0:
        return [], [], [], []
    if n == 1:
        return X, X, y, y

    rng = random.Random(random_state)
    indices = list(range(n))
    rng.shuffle(indices)

    test_count = max(1, int(round(n * test_size)))
    if test_count >= n:
        test_count = n - 1

    test_indices = set(indices[:test_count])
    train_indices = [i for i in indices if i not in test_indices]

    X_train = [X[i] for i in train_indices]
    y_train = [y[i] for i in train_indices]
    X_test = [X[i] for i in test_indices]
    y_test = [y[i] for i in test_indices]

    return X_train, X_test, y_train, y_test


class SimpleRandomForestProxyClassifier:
    """
    A standalone decision tree ensemble implementation
    that mirrors Random Forest classification and feature importance.
    """

    def __init__(self, n_estimators: int = 25, random_state: int = 42, feature_names: Optional[List[str]] = None):
        self.n_estimators = n_estimators
        self.random_state = random_state
        self.feature_names = feature_names or []
        self.trees: List[Dict[str, Any]] = []
        self.feature_importances_: Dict[str, float] = {}

    def fit(self, X: List[List[float]], y: List[int]) -> "SimpleRandomForestProxyClassifier":
        rng = random.Random(self.random_state)
        n_samples = len(X)
        if n_samples == 0:
            return self

        n_features = len(X[0])
        splits_count = {i: 0 for i in range(n_features)}

        self.trees = []
        for _ in range(self.n_estimators):
            # Bootstrap sample
            boot_idx = [rng.randint(0, n_samples - 1) for _ in range(n_samples)]
            X_boot = [X[i] for i in boot_idx]
            y_boot = [y[i] for i in boot_idx]

            # Find best split on random feature subset
            feature_idx = rng.randint(0, n_features - 1)
            vals = [X_boot[i][feature_idx] for i in range(n_samples)]
            threshold = sum(vals) / len(vals) if vals else 0.0

            splits_count[feature_idx] += 1

            # Simple decision stump rule
            # Left: < threshold, Right: >= threshold
            left_pos = sum(1 for i in range(n_samples) if vals[i] < threshold and y_boot[i] == 1)
            left_total = sum(1 for i in range(n_samples) if vals[i] < threshold) or 1
            right_pos = sum(1 for i in range(n_samples) if vals[i] >= threshold and y_boot[i] == 1)
            right_total = sum(1 for i in range(n_samples) if vals[i] >= threshold) or 1

            pred_left = 1 if (left_pos / left_total) >= 0.5 else 0
            pred_right = 1 if (right_pos / right_total) >= 0.5 else 0

            self.trees.append({
                "feature": feature_idx,
                "threshold": threshold,
                "pred_left": pred_left,
                "pred_right": pred_right,
            })

        # Calculate normalized feature importances
        total_splits = sum(splits_count.values()) or 1
        self.feature_importances_ = {}
        for idx, count in splits_count.items():
            name = self.feature_names[idx] if idx < len(self.feature_names) else f"feature_{idx}"
            self.feature_importances_[name] = round(count / total_splits, 3)

        return self

    def predict(self, X: List[List[float]]) -> List[int]:
        if not self.trees:
            return [0] * len(X)

        predictions = []
        for row in X:
            votes = 0
            for tree in self.trees:
                feat = tree["feature"]
                val = row[feat]
                pred = tree["pred_right"] if val >= tree["threshold"] else tree["pred_left"]
                votes += pred
            # Majority vote
            predictions.append(1 if (votes / len(self.trees)) >= 0.5 else 0)
        return predictions


class MLPipelineEvaluator:
    """
    Evaluates weather dataset using proper Train/Test split methodology
    and proxy disaster risk label formulation.
    """

    def __init__(self, random_state: int = 42, test_size: float = 0.25):
        self.random_state = random_state
        self.test_size = test_size

    def generate_proxy_labels(
        self, weather_records: List[WeatherResult], disaster_type: str = "flood"
    ) -> Tuple[List[List[float]], List[int], List[str]]:
        """
        Generates proxy labels following the repository's rule formulas.
        Returns: (feature_matrix X, proxy_labels y, feature_names)
        """
        if not weather_records:
            return [], [], []

        if disaster_type == "flood":
            feature_names = ["wind_speed", "precipitation", "humidity", "soil_moisture"]
            # Threshold = mean of humidity & soil_moisture*100
            avg_hum = sum(w.humidity for w in weather_records) / len(weather_records)
            avg_soil = sum(w.soil_moisture for w in weather_records) / len(weather_records)
            threshold = (avg_hum + avg_soil * 100.0) / 2.0

            X = []
            y = []
            for w in weather_records:
                X.append([w.wind_speed, w.precipitation, w.humidity, w.soil_moisture])
                score = w.humidity * 0.5 + w.soil_moisture * 100.0
                y.append(1 if score >= threshold else 0)
            return X, y, feature_names

        else:
            # Heatwave
            feature_names = ["temperature", "heat_index"]
            heat_indices = [w.temperature + 0.33 * w.humidity - 0.7 for w in weather_records]
            threshold = sum(heat_indices) / len(heat_indices) if heat_indices else 35.0

            X = []
            y = []
            for w, hi in zip(weather_records, heat_indices):
                X.append([w.temperature, round(hi, 2)])
                y.append(1 if hi >= threshold else 0)
            return X, y, feature_names

    def evaluate(
        self,
        weather_records: List[WeatherResult],
        disaster_type: str = "flood",
    ) -> EvaluationMetrics:
        """
        Executes train/test split, fits Random Forest, evaluates on held-out test split,
        and computes accuracy, precision, recall, f1, confusion matrix, and feature importances.
        """
        X, y, feature_names = self.generate_proxy_labels(weather_records, disaster_type=disaster_type)

        if len(X) < 4:
            # Not enough data for meaningful split
            X_train, X_test, y_train, y_test = X, X, y, y
        else:
            X_train, X_test, y_train, y_test = train_test_split_dataset(
                X, y, test_size=self.test_size, random_state=self.random_state
            )

        # Train model strictly on training set
        model = SimpleRandomForestProxyClassifier(
            n_estimators=30, random_state=self.random_state, feature_names=feature_names
        )
        model.fit(X_train, y_train)

        # Evaluate strictly on held-out test set
        y_pred = model.predict(X_test)

        acc = compute_accuracy(y_test, y_pred)
        prec = compute_precision(y_test, y_pred, positive_class=1)
        rec = compute_recall(y_test, y_pred, positive_class=1)
        f1 = compute_f1(prec, rec)
        cm = compute_confusion_matrix(y_test, y_pred)

        class_names = {0: "Safe", 1: "Danger" if disaster_type == "flood" else "Heatwave"}
        report = build_classification_report(y_test, y_pred, class_names)

        return EvaluationMetrics(
            accuracy=acc,
            precision=prec,
            recall=rec,
            f1=f1,
            confusion_matrix=cm,
            classification_report=report,
            feature_importance=model.feature_importances_,
            train_size=len(X_train),
            test_size=len(X_test),
            random_state=self.random_state,
            is_proxy_label=True,
            disclaimer=PROXY_LABEL_DISCLAIMER,
        )

    def ingest_and_evaluate(
        self,
        locations: List[Dict[str, Any]],
        weather_service: WeatherService,
        disaster_type: str = "flood",
    ) -> EvaluationMetrics:
        """
        Ingests real or mocked weather for given coordinates via WeatherService,
        then evaluates ML pipeline on held-out test split.
        """
        weather_records: List[WeatherResult] = []
        for loc in locations:
            lat = float(loc["lat"])
            lon = float(loc["lon"])
            w = weather_service.get_weather(lat, lon, raise_on_error=False)
            if w.is_success:
                weather_records.append(w)

        return self.evaluate(weather_records, disaster_type=disaster_type)
